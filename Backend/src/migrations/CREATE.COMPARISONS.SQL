CREATE TABLE IF NOT EXISTS public."REPORT_COMPARISONS"
(
    "COMPARISON_ID" uuid NOT NULL DEFAULT gen_random_uuid(),

    "USER_ID" uuid NOT NULL,

    "REPORT_1_ID" uuid NOT NULL,
    "REPORT_2_ID" uuid NOT NULL,

    "COMPARED_AT" timestamp without time zone
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    "COMPARISON_RESULT" jsonb NOT NULL,

    CONSTRAINT "REPORT_COMPARISONS_pkey"
        PRIMARY KEY ("COMPARISON_ID"),

    CONSTRAINT "REPORT_COMPARISONS_USER_ID_fkey"
        FOREIGN KEY ("USER_ID")
        REFERENCES public."USERS" ("USER_ID")
        ON DELETE CASCADE,

    CONSTRAINT "REPORT_COMPARISONS_REPORT_1_ID_fkey"
        FOREIGN KEY ("REPORT_1_ID")
        REFERENCES public."REPORTS" ("REPORT_ID")
        ON DELETE CASCADE,

    CONSTRAINT "REPORT_COMPARISONS_REPORT_2_ID_fkey"
        FOREIGN KEY ("REPORT_2_ID")
        REFERENCES public."REPORTS" ("REPORT_ID")
        ON DELETE CASCADE,

    CONSTRAINT "REPORT_COMPARISONS_DIFFERENT_REPORTS"
        CHECK ("REPORT_1_ID" <> "REPORT_2_ID")
);

CREATE INDEX IF NOT EXISTS "idx_report_comparisons_user_id"
ON public."REPORT_COMPARISONS" ("USER_ID");

CREATE INDEX IF NOT EXISTS "idx_report_comparisons_report_1_id"
ON public."REPORT_COMPARISONS" ("REPORT_1_ID");

CREATE INDEX IF NOT EXISTS "idx_report_comparisons_report_2_id"
ON public."REPORT_COMPARISONS" ("REPORT_2_ID");

CREATE INDEX IF NOT EXISTS "idx_report_comparisons_compared_at"
ON public."REPORT_COMPARISONS" ("COMPARED_AT" DESC);