

CREATE TABLE IF NOT EXISTS public."CHAT_SESSIONS" (
    "CHAT_ID" UUID NOT NULL DEFAULT gen_random_uuid(),
    "USER_ID" UUID NOT NULL,
    "REPORT_ID" UUID NOT NULL,

    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    "UPDATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "CHAT_SESSIONS_pkey"
        PRIMARY KEY ("CHAT_ID"),

    CONSTRAINT "CHAT_SESSIONS_USER_ID_fkey"
        FOREIGN KEY ("USER_ID")
        REFERENCES public."USERS" ("USER_ID")
        ON DELETE CASCADE,

    CONSTRAINT "CHAT_SESSIONS_REPORT_ID_fkey"
        FOREIGN KEY ("REPORT_ID")
        REFERENCES public."REPORTS" ("REPORT_ID")
        ON DELETE CASCADE,

    CONSTRAINT "CHAT_SESSIONS_REPORT_ID_unique"
        UNIQUE ("REPORT_ID")
);


CREATE TABLE IF NOT EXISTS public."CHAT_MESSAGES" (
    "MESSAGE_ID" UUID NOT NULL DEFAULT gen_random_uuid(),
    "CHAT_ID" UUID NOT NULL,

    "ROLE" VARCHAR(20) NOT NULL,
    "MESSAGE" TEXT NOT NULL,

    "CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "CHAT_MESSAGES_pkey"
        PRIMARY KEY ("MESSAGE_ID"),

    CONSTRAINT "CHAT_MESSAGES_CHAT_ID_fkey"
        FOREIGN KEY ("CHAT_ID")
        REFERENCES public."CHAT_SESSIONS" ("CHAT_ID")
        ON DELETE CASCADE,

    CONSTRAINT "CHAT_MESSAGES_ROLE_check"
        CHECK ("ROLE" IN ('USER', 'ASSISTANT', 'SYSTEM'))
);

